#!/usr/bin/env python3
"""Per-agent call-distribution report from a run log.

The specification caps any single agent at 40% of the LLM and tool calls in a
typical scenario, and requires the claim to be backed by logs. This reads the
JSONL log a run produced and prints the distribution, exiting non-zero if the cap
is breached — so it works as a check in CI as well as a figure for the report.

    python tools/load_report.py                     # newest log
    python tools/load_report.py logs/run-*.jsonl    # specific logs, combined
    python tools/load_report.py --markdown          # table for the report
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LIMIT = 0.40


def read_records(paths: list[Path]):
    for path in paths:
        with path.open(encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    yield json.loads(line)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("logs", nargs="*", help="log files (default: the newest run log)")
    parser.add_argument("--markdown", action="store_true", help="emit a markdown table")
    parser.add_argument("--limit", type=float, default=LIMIT, help="per-agent cap (default 0.40)")
    args = parser.parse_args()

    if args.logs:
        paths = [Path(p) for pattern in args.logs for p in glob.glob(pattern)] or [
            Path(p) for p in args.logs
        ]
    else:
        candidates = sorted((REPO_ROOT / "logs").glob("run-*.jsonl"))
        if not candidates:
            print("no run logs found; run `safeschool demo` first", file=sys.stderr)
            return 1
        paths = [candidates[-1]]

    missing = [p for p in paths if not p.exists()]
    if missing:
        print(f"log file(s) not found: {', '.join(str(p) for p in missing)}", file=sys.stderr)
        return 1

    counts: dict[str, dict[str, int]] = defaultdict(
        lambda: {"tool": 0, "llm": 0, "agent": 0, "error": 0, "ms": 0.0,
                 "tokens_in": 0, "tokens_out": 0}
    )
    cases: set[str] = set()
    for record in read_records(paths):
        bucket = counts[record["agent"]]
        cases.add(record.get("case_id", "?"))
        if record["event"] in {"tool", "llm", "agent", "error"}:
            bucket[record["event"]] += 1
        bucket["ms"] += record.get("duration_ms", 0.0)
        bucket["tokens_in"] += record.get("tokens_in", 0) or 0
        bucket["tokens_out"] += record.get("tokens_out", 0) or 0

    billable = {a: c["tool"] + c["llm"] for a, c in counts.items()}
    total = sum(billable.values())
    if total == 0:
        print("no tool or LLM calls recorded", file=sys.stderr)
        return 1

    ordered = sorted(billable.items(), key=lambda kv: -kv[1])
    worst_agent, worst_count = ordered[0]
    worst_share = worst_count / total
    sources = ", ".join(p.name for p in paths)

    if args.markdown:
        print(f"<!-- generated by tools/load_report.py from {sources} -->")
        print(f"\n**{len(cases)} case(s), {total} tool+LLM calls**\n")
        print("| agent | tool calls | LLM calls | share | tokens in/out |")
        print("|---|---:|---:|---:|---:|")
        for agent, value in ordered:
            c = counts[agent]
            print(f"| `{agent}` | {c['tool']} | {c['llm']} | {value / total * 100:.1f}% | "
                  f"{c['tokens_in']}/{c['tokens_out']} |")
        print(f"| **total** | | | **{total} calls** | |")
        verdict = "within" if worst_share <= args.limit else "ABOVE"
        print(f"\nBusiest agent: `{worst_agent}` at {worst_share * 100:.1f}% — "
              f"{verdict} the {args.limit * 100:.0f}% limit.")
    else:
        print(f"\nCall distribution ({sources}; {len(cases)} case(s))\n")
        print(f"  {'agent':24s} {'tool':>5s} {'llm':>4s} {'share':>7s}  {'time':>9s}")
        for agent, value in ordered:
            c = counts[agent]
            share = value / total
            flag = "  <-- OVER LIMIT" if share > args.limit else ""
            print(f"  {agent:24s} {c['tool']:5d} {c['llm']:4d} {share * 100:6.1f}% "
                  f" {c['ms']:8.0f}ms  {'#' * max(0, int(share * 30))}{flag}")
        print(f"  {'TOTAL':24s} {sum(c['tool'] for c in counts.values()):5d} "
              f"{sum(c['llm'] for c in counts.values()):4d} {total:6d} calls")

    if worst_share > args.limit:
        print(f"\nFAIL: {worst_agent} holds {worst_share * 100:.1f}% "
              f"(limit {args.limit * 100:.0f}%)", file=sys.stderr)
        return 1
    print(f"\nOK: busiest agent ({worst_agent}) holds {worst_share * 100:.1f}% "
          f"of {total} calls, limit {args.limit * 100:.0f}%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
